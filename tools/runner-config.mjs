// Makes workers/<runner>/wrangler.staging.jsonc from wrangler.jsonc: `staging` gets its own Worker name and its own queue, so a staging runner can never take a production run.
// Usage: node tools/runner-config.mjs <staging|production> [find-jobs|apply]   (default find-jobs; production writes nothing: the committed wrangler.jsonc is the production config)
// Why (5 Nov 2026, hr 2/6): the committed config consumes the production queue, the one www fills. A staging deploy of that same file would also read it, steal production's runs and run them
// against the wrong site. The staging file renames the Worker and the queue and caps the instances; nothing else changes (same image, same container class).
// Why (13 Nov 2026, plan 2026-11-13-cloud-runners.md 3/3; owner: "Yes, staging for all three"): the Apply runner gets the same staging copy.
import {readFileSync, writeFileSync} from 'node:fs';

export const RUNNERS = {
  'find-jobs': {dir: 'workers/hosted-runner', queue: 'find-jobs-runs', staging: {name: 'find-jobs-runner-staging', queue: 'find-jobs-runs-staging', maxInstances: 2}},
  apply: {dir: 'workers/ready-runner', queue: 'apply-runs', staging: {name: 'apply-runner-staging', queue: 'apply-runs-staging', maxInstances: 2}},
};
export const STAGING = RUNNERS['find-jobs'].staging;

/** The committed config as an object: it is JSON with whole-line `//` comments. */
export function readConfig(text) {
  return JSON.parse(text.split('\n').filter(line => !/^\s*\/\//.test(line)).join('\n'));
}

/** The staging copy of a runner config (`runner`: find-jobs | apply): own name, own queue, few instances. Throws when the result could still touch production. */
export function stagingConfig(config, runner = 'find-jobs') {
  const {queue, staging} = RUNNERS[runner], out = structuredClone(config);
  out.name = staging.name;
  out.queues = {consumers: config.queues.consumers.map(consumer => ({...consumer, queue: staging.queue}))};
  out.containers = config.containers.map(container => ({...container, max_instances: staging.maxInstances}));
  if (out.name === config.name || out.queues.consumers.some(consumer => consumer.queue === queue)) throw new Error('staging runner config still has the production name or queue');
  return out;
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file://').href) {
  const [target, runner = 'find-jobs'] = process.argv.slice(2);
  if (!['staging', 'production'].includes(target) || !RUNNERS[runner]) { console.error('usage: node tools/runner-config.mjs <staging|production> [find-jobs|apply]'); process.exit(2); }
  if (target === 'staging') {
    const {dir} = RUNNERS[runner], config = stagingConfig(readConfig(readFileSync(`${dir}/wrangler.jsonc`, 'utf8')), runner);
    writeFileSync(`${dir}/wrangler.staging.jsonc`, `// GENERATED by tools/runner-config.mjs: the staging copy of wrangler.jsonc, never committed.\n${JSON.stringify(config, null, 2)}\n`);
  }
  console.log(`runner config: ${target} ${runner}`);
}
